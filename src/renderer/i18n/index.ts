export const dictionaries: Readonly<Record<Language, Readonly<Record<TranslationKey, string>>>> = {
  zh,
  en,
};

export function t(
  language: Language,
  key: TranslationKey,
  values: Readonly<Record<string, string | number>> = {},
): string {
  return dictionaries[language][key].replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    name in values ? String(values[name]) : placeholder,
  );
}

export function localize(language: Language, value: LocalizedText | string): string {
  return typeof value === 'string' ? value : value[language];
}

export function localized(zh: string, en: string): LocalizedText {
  return { zh, en };
}
